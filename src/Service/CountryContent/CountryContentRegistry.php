    /**
     * Which of the club-generation content categories are missing for this country —
     * the diagnostic `app:country:check` reports so gaps are visible instead of silently
     * falling back to generic placeholder names.
     *
     * @return string[]
     */
    public static function missingCategories(Country $country): array
    {
        $missing = [];
        if (self::places($country) === null) {
            $missing[] = 'places';
        }
        if (self::prestigeSuffixes($country) === []) {
            $missing[] = 'prestigeSuffixes';
        }
        if (self::genericSuffixes($country) === []) {
            $missing[] = 'genericSuffixes';
        }
        if (self::stadiumFormats($country) === []) {
            $missing[] = 'stadiumFormats';
        }

        return $missing;
    }
